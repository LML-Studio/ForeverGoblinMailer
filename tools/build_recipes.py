"""Generate the locale-independent ingredient index from decoded Forever client tables."""
import argparse
import csv
from collections import defaultdict
from hashlib import sha256
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ROLES = {129:"firstaid", 164:"smith", 165:"leatherworker", 171:"alchemist", 182:"herbalist",
         185:"cook", 186:"miner", 197:"tailor", 202:"engineer", 333:"enchanter", 356:"fisher", 393:"skinner"}


def rows(path):
    with path.open(encoding="utf-8-sig", newline="") as stream:
        yield from csv.DictReader(stream)


def generate(tables, build):
    skills = {int(row["ID"]) for row in rows(tables / "SkillLine.csv")}
    if not ROLES.keys() <= skills:
        raise ValueError("Selected skills are absent from this client")
    abilities = defaultdict(set)
    for row in rows(tables / "SkillLineAbility.csv"):
        skill = int(row["SkillLine"])
        if skill in ROLES:
            abilities[int(row["Spell"])].add(ROLES[skill])
    by_role = defaultdict(set)
    for row in rows(tables / "SpellReagents.csv"):
        for role in abilities.get(int(row["SpellID"]), ()):
            for i in range(8):
                reagent = int(row[f"Reagent[{i}]"])
                if reagent > 0 and int(row[f"ReagentCount[{i}]"]) > 0:
                    by_role[role].add(reagent)
    lines = [f"-- Generated by tools/build_recipes.py for Forever {build}.", "local _, M = ...",
             "M.recipeOwners = {}", "local function register(role, ids)",
             "    for _, id in ipairs(ids) do", "        local owners = M.recipeOwners[id] or {}",
             "        M.recipeOwners[id] = owners", "        owners[#owners + 1] = role",
             "    end", "end", ""]
    for role, ids in sorted(by_role.items()):
        values = [str(n) for n in sorted(ids)]
        lines.append(f'register("{role}", {{')
        for i in range(0, len(values), 15):
            lines.append("    " + ", ".join(values[i:i+15]) + ",")
        lines.append("})")
    target = ROOT / "ForeverGoblinMailer" / "Recipes.lua"
    target.write_bytes(("\n".join(lines) + "\n").encode())
    unique = set().union(*by_role.values())
    print(f"{len(unique)} distinct ingredients, {sum(map(len, by_role.values()))} profession links")
    for table in ("SkillLine", "SkillLineAbility", "SpellReagents"):
        print(table, sha256((tables / (table + ".csv")).read_bytes()).hexdigest())


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("tables", type=Path)
    parser.add_argument("--build", required=True)
    args = parser.parse_args()
    generate(args.tables, args.build)
